    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        Integer numero;
        LocalDate fechaSinFormato;
        
        try {
        // Convertimos el texto del campo a fecha (formato dd/MM/yyyy)
        DateTimeFormatter formato = DateTimeFormatter.ofPattern("dd/MM/yyyy");
        fechaSinFormato = LocalDate.parse(fechaField.getText().trim(), formato);

        // El número también puede fallar si no escriben un entero
        numero = Integer.valueOf(numeroField.getText().trim());
        } catch (DateTimeParseException | NumberFormatException ex) {
            errorjLabel.setText(textoErrorGuardado);
            return; // salimos: no seguimos con datos inválidos
        }

        if (ControladorClientes.comprobarFecha(fechaSinFormato) && ControladorClientes.ComprobarPuntos(puntosField.getText())) {
            control.anadirCliente(nombreField.getText(), numero, puntosField.getText(), fechaSinFormato);
            errorjLabel.setText("");
            System.out.println("Se ha completado el alta");
        } else {
            errorjLabel.setText(textoErrorGuardado);
        }
    }//GEN-LAST:event_jButton1ActionPerformed

